#!/usr/bin/env python3
"""
Server-side A4 psychometric report PDF generator (ReportLab + matplotlib).
Called from the Next.js API route via child_process.

Usage:
  python3 report.py <input_json_path> <output_pdf_path>

Input JSON shape:
{
  "platform": "Psychometric Testing Platform",
  "reportId": "...",
  "student": {"name","email","phone"},
  "assessment": {"title","purpose","category"},
  "attempt": {"startedAt","completedAt"},
  "score": {
    "dimensions":[{"code","name","score","maxScore","pct","level","description"}],
    "totalScore": int|null,
    "recommendation": "...",
    "topDimensions": ["..."],
    "domainBreakdown": [{"code","title","aptitude","interest","composite"}]  // optional
  }
}
"""
import sys, os, json, tempfile
from datetime import datetime

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_LEFT, TA_CENTER, TA_RIGHT
from reportlab.platypus import (
    BaseDocTemplate, PageTemplate, Frame, Paragraph, Spacer, Table, TableStyle,
    Image, PageBreak, KeepTogether,
)
from reportlab.pdfgen import canvas

# --- Palette (professional, non-indigo/blue-primary) -----------------------
NAVY = colors.HexColor("#0F2A43")
TEAL = colors.HexColor("#0E7C66")
AMBER = colors.HexColor("#B45309")
SLATE = colors.HexColor("#334155")
MUTED = colors.HexColor("#64748B")
LIGHT = colors.HexColor("#F1F5F9")
BORDER = colors.HexColor("#CBD5E1")
GREEN = colors.HexColor("#15803D")
ROSE = colors.HexColor("#BE123C")

PAGE_W, PAGE_H = A4
MARGIN = 18 * mm
CONTENT_W = PAGE_W - 2 * MARGIN


def build_chart(score, tmpdir):
    """Horizontal bar chart of dimension percentages -> PNG path."""
    dims = score.get("dimensions", [])[:12]  # cap for readability
    if not dims:
        return None
    labels = [d["name"][:28] for d in dims]
    pcts = [d.get("pct", 0) for d in dims]
    levels = [d.get("level", "") for d in dims]

    fig, ax = plt.subplots(figsize=(7.2, max(2.2, 0.42 * len(dims) + 0.8)))
    bar_colors = []
    for p in pcts:
        if p >= 70:
            bar_colors.append("#15803D")
        elif p >= 40:
            bar_colors.append("#0E7C66")
        else:
            bar_colors.append("#B45309")
    y = range(len(labels))
    ax.barh(y, pcts, color=bar_colors, height=0.62, zorder=3)
    ax.set_yticks(list(y))
    ax.set_yticklabels(labels, fontsize=9, color="#0F2A43")
    ax.invert_yaxis()
    ax.set_xlim(0, 100)
    ax.set_xlabel("Score (%)", fontsize=9, color="#334155")
    ax.set_title("Dimension Profile", fontsize=11, color="#0F2A43", fontweight="bold", pad=10)
    ax.tick_params(axis="x", labelsize=8, colors="#64748B")
    ax.grid(axis="x", color="#E2E8F0", linewidth=0.8, zorder=0)
    for spine in ["top", "right"]:
        ax.spines[spine].set_visible(False)
    for spine in ["left", "bottom"]:
        ax.spines[spine].set_color("#CBD5E1")
    for i, p in enumerate(pcts):
        ax.text(p + 1.5, i, f"{p}%", va="center", fontsize=8, color="#334155", fontweight="bold")
    plt.tight_layout()
    path = os.path.join(tmpdir, "chart.png")
    fig.savefig(path, dpi=180, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return path


def header_footer(canv: canvas.Canvas, doc):
    """Professional header + footer with page numbers on every page."""
    canv.saveState()
    # Header band
    canv.setFillColor(NAVY)
    canv.rect(0, PAGE_H - 14 * mm, PAGE_W, 14 * mm, fill=1, stroke=0)
    canv.setFillColor(colors.white)
    canv.setFont("Helvetica-Bold", 10)
    canv.drawString(MARGIN, PAGE_H - 9 * mm, "Psychometric Testing Platform")
    canv.setFont("Helvetica", 8)
    canv.drawRightString(PAGE_W - MARGIN, PAGE_H - 9 * mm, "Confidential Assessment Report")
    # Footer
    canv.setStrokeColor(BORDER)
    canv.setLineWidth(0.5)
    canv.line(MARGIN, 12 * mm, PAGE_W - MARGIN, 12 * mm)
    canv.setFillColor(MUTED)
    canv.setFont("Helvetica", 7.5)
    canv.drawString(MARGIN, 8 * mm, "This report is generated by the Psychometric Testing Platform and is intended for authorised recipients only.")
    canv.drawRightString(PAGE_W - MARGIN, 8 * mm, f"Page {doc.page}")
    canv.restoreState()


def fmt_date(s):
    if not s:
        return "—"
    try:
        return datetime.fromisoformat(s.replace("Z", "")).strftime("%d %b %Y, %I:%M %p")
    except Exception:
        return str(s)


def build(data, out_path):
    styles = getSampleStyleSheet()
    H1 = ParagraphStyle("H1", parent=styles["Heading1"], fontSize=18, textColor=NAVY, spaceAfter=6, leading=22)
    H2 = ParagraphStyle("H2", parent=styles["Heading2"], fontSize=13, textColor=TEAL, spaceBefore=12, spaceAfter=5, leading=16)
    BODY = ParagraphStyle("Body", parent=styles["Normal"], fontSize=10, textColor=SLATE, leading=14, spaceAfter=4)
    SMALL = ParagraphStyle("Small", parent=styles["Normal"], fontSize=8.5, textColor=MUTED, leading=11)
    REC = ParagraphStyle("Rec", parent=BODY, fontSize=11, textColor=NAVY, leading=15, spaceAfter=6)

    story = []
    student = data.get("student", {})
    assessment = data.get("assessment", {})
    attempt = data.get("attempt", {})
    score = data.get("score", {})
    dims = score.get("dimensions", [])

    # Title
    story.append(Paragraph("Psychometric Assessment Report", H1))
    story.append(Paragraph(f"{assessment.get('title', 'Assessment')}", ParagraphStyle("Sub", parent=BODY, fontSize=12, textColor=TEAL, fontweight="bold" if False else None, leading=15)))
    story.append(Spacer(1, 8))

    # Student info table
    info_rows = [
        ["Student Name", student.get("name", "—"), "Email", student.get("email", "—")],
        ["Mobile", student.get("phone", "—"), "Category", assessment.get("category", "—")],
        ["Assessment Date", fmt_date(attempt.get("completedAt") or attempt.get("startedAt")), "Report ID", data.get("reportId", "—")[:12]],
    ]
    info_tbl = Table(info_rows, colWidths=[28 * mm, 62 * mm, 28 * mm, 56 * mm])
    info_tbl.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), MUTED),
        ("TEXTCOLOR", (2, 0), (2, -1), MUTED),
        ("TEXTCOLOR", (1, 0), (1, -1), SLATE),
        ("TEXTCOLOR", (3, 0), (3, -1), SLATE),
        ("FONTNAME", (1, 0), (1, -1), "Helvetica-Bold"),
        ("FONTNAME", (3, 0), (3, -1), "Helvetica-Bold"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, BORDER),
    ]))
    story.append(info_tbl)
    story.append(Spacer(1, 10))

    # Purpose
    if assessment.get("purpose"):
        story.append(Paragraph("About This Assessment", H2))
        story.append(Paragraph(assessment["purpose"], BODY))
        story.append(Spacer(1, 6))

    # Recommendation callout
    if score.get("recommendation"):
        story.append(Paragraph("Key Recommendation", H2))
        rec_tbl = Table([[Paragraph(score["recommendation"], REC)]], colWidths=[CONTENT_W])
        rec_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ECFDF5")),
            ("BOX", (0, 0), (-1, -1), 0.75, GREEN),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(rec_tbl)
        story.append(Spacer(1, 10))

    # Chart
    tmpdir = tempfile.mkdtemp()
    chart_path = build_chart(score, tmpdir)
    if chart_path:
        story.append(Paragraph("Dimension Profile", H2))
        img = Image(chart_path, width=CONTENT_W, height=CONTENT_W * 0.5)
        img._restrictSize(CONTENT_W, 120 * mm)
        story.append(img)
        story.append(Spacer(1, 8))

    # Domain breakdown (stream-selector style)
    if score.get("domainBreakdown"):
        story.append(Paragraph("Stream Comparison", H2))
        br = score["domainBreakdown"]
        br_rows = [["Rank", "Stream", "Aptitude", "Interest", "Composite"]]
        for i, b in enumerate(br):
            br_rows.append([str(i + 1), b.get("title", b.get("code", "—")), f"{b.get('aptitude', 0)}", f"{b.get('interest', 0)}", f"{b.get('composite', 0)}"])
        br_tbl = Table(br_rows, colWidths=[14 * mm, 70 * mm, 28 * mm, 28 * mm, 32 * mm], repeatRows=1)
        br_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("ALIGN", (0, 0), (0, -1), "CENTER"),
            ("ALIGN", (2, 0), (-1, -1), "CENTER"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
            ("GRID", (0, 0), (-1, -1), 0.25, BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(br_tbl)
        story.append(Spacer(1, 10))

    # Dimension details table
    if dims:
        story.append(Paragraph("Detailed Dimension Breakdown", H2))
        rows = [["Dimension", "Score", "Max", "%", "Level"]]
        for d in dims:
            rows.append([d.get("name", d.get("code", "—")), str(d.get("score", 0)), str(d.get("maxScore", 0)), f"{d.get('pct', 0)}%", d.get("level", "—")])
        dt = Table(rows, colWidths=[78 * mm, 22 * mm, 22 * mm, 22 * mm, 28 * mm], repeatRows=1)
        dt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("ALIGN", (1, 0), (-1, -1), "CENTER"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
            ("GRID", (0, 0), (-1, -1), 0.25, BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(dt)
        story.append(Spacer(1, 8))

        # Interpretation per dimension (top 6 to keep report focused)
        story.append(Paragraph("Interpretation Notes", H2))
        for d in dims[:8]:
            lvl = d.get("level", "")
            lvl_color = GREEN if lvl in ("High", "Dominant") else TEAL if lvl in ("Moderate",) else AMBER
            para = Paragraph(
                f'<b>{d.get("name", d.get("code"))}</b> — {d.get("pct", 0)}% ({lvl}). {d.get("description", "")}',
                BODY,
            )
            tbl = Table([[para]], colWidths=[CONTENT_W])
            tbl.setStyle(TableStyle([
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LINEBEFORE", (0, 0), (0, -1), 2.5, lvl_color),
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FAFAFA")),
            ]))
            story.append(KeepTogether([tbl, Spacer(1, 4)]))

    # Disclaimer
    story.append(Spacer(1, 12))
    story.append(Paragraph("Important Note", H2))
    story.append(Paragraph(
        "This report is based on a self-report psychometric screening instrument and is intended for guidance purposes only. "
        "It is not a clinical diagnosis. Results should be interpreted alongside one-to-one counselling, academic records and other "
        "relevant context. For career-critical decisions, please consult a qualified career counsellor.",
        SMALL,
    ))

    # Build the document
    doc = BaseDocTemplate(out_path, pagesize=A4, leftMargin=MARGIN, rightMargin=MARGIN, topMargin=20 * mm, bottomMargin=16 * mm,
                          title=f"{assessment.get('title','Assessment')} Report - {student.get('name','Student')}",
                          author="Psychometric Testing Platform", subject="Psychometric Assessment Report", creator="Psychometric Testing Platform")
    frame = Frame(MARGIN, 16 * mm, CONTENT_W, PAGE_H - 36 * mm, id="main", showBoundary=0)
    doc.addPageTemplates([PageTemplate(id="all", frames=[frame], onPage=header_footer)])
    doc.build(story)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: report.py <input_json> <output_pdf>", file=sys.stderr)
        sys.exit(2)
    with open(sys.argv[1], "r", encoding="utf-8") as f:
        data = json.load(f)
    build(data, sys.argv[2])
    print(f"OK {sys.argv[2]}", file=sys.stdout)
